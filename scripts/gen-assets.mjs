// Embeds the GUI files into src/gui/assets.gen.ts so the CLI (and the
// single-file binaries) never need an external assets directory at runtime.
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const names = ["index.html", "app.js", "app.css"];

const entries = await Promise.all(
  names.map(async (name) => [name, await readFile(join(root, "assets", name), "utf8")]),
);

const body = entries
  .map(([name, content]) => `  ${JSON.stringify(name)}: ${JSON.stringify(content)},`)
  .join("\n");

const out = `// Generated by scripts/gen-assets.mjs — do not edit.
// Source of truth: assets/index.html, assets/app.js, assets/app.css
export const assets: Record<string, string> = {
${body}
};
`;

const target = join(root, "src", "gui", "assets.gen.ts");
await mkdir(dirname(target), { recursive: true });
await writeFile(target, out, "utf8");
console.log(`gen-assets: ${names.join(", ")} -> src/gui/assets.gen.ts`);
